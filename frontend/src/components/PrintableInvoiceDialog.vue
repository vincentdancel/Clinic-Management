<script setup lang="ts">
import {
  formatCurrency,
  formatDate,
  INVOICE_STATUS_META,
  type InvoiceRecord,
} from '@/types/billing'

const props = defineProps<{
  modelValue: boolean
  invoice: InvoiceRecord | null
}>()

const emit = defineEmits<{
  'update:modelValue': [value: boolean]
}>()

function printInvoice() {
  if (!props.invoice) return
  const inv = props.invoice
  const statusLabel = INVOICE_STATUS_META[inv.status]?.label ?? inv.status
  const rows = (inv.items ?? [])
    .map(
      (item) => `
      <tr>
        <td>${item.description}</td>
        <td style="text-transform:capitalize;">${item.item_type}</td>
        <td class="right">${Number(item.quantity)}</td>
        <td class="right">${formatCurrency(item.unit_price)}</td>
        <td class="right">${formatCurrency(item.line_total)}</td>
      </tr>`,
    )
    .join('')

  const win = window.open('', '_blank', 'width=840,height=920')
  if (!win) return

  win.document.write(`<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <title>Invoice ${inv.invoice_number}</title>
  <style>
    body { font-family: Arial, Helvetica, sans-serif; color: #1f2937; margin: 32px; }
    .header { display: flex; justify-content: space-between; border-bottom: 2px solid #0f766e; padding-bottom: 16px; margin-bottom: 20px; }
    .clinic { font-size: 20px; font-weight: 700; color: #0f766e; }
    .sub { font-size: 12px; color: #6b7280; margin-top: 4px; }
    .doc-title { text-align: right; }
    .doc-title h1 { margin: 0; font-size: 22px; }
    .doc-title p { margin: 4px 0 0; font-size: 13px; color: #4b5563; }
    .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 16px; margin-bottom: 24px; font-size: 13px; }
    .box { background: #f9fafb; border: 1px solid #e5e7eb; border-radius: 6px; padding: 12px; }
    .label { font-size: 11px; text-transform: uppercase; color: #6b7280; margin-bottom: 4px; }
    table { width: 100%; border-collapse: collapse; font-size: 13px; }
    th, td { border-bottom: 1px solid #e5e7eb; padding: 10px 8px; text-align: left; }
    th { background: #f3f4f6; font-size: 11px; text-transform: uppercase; color: #4b5563; }
    .right { text-align: right; }
    .summary { width: 300px; margin-left: auto; margin-top: 20px; font-size: 13px; }
    .summary-row { display: flex; justify-content: space-between; padding: 5px 0; }
    .summary-total { border-top: 2px solid #1f2937; margin-top: 6px; padding-top: 8px; font-weight: 700; font-size: 15px; }
    .footer { margin-top: 40px; font-size: 12px; color: #6b7280; text-align: center; border-top: 1px dashed #d1d5db; padding-top: 16px; }
  </style>
</head>
<body>
  <div class="header">
    <div>
      <div class="clinic">CLINIC CARE MANAGEMENT</div>
      <div class="sub">Patient Billing Statement</div>
    </div>
    <div class="doc-title">
      <h1>INVOICE</h1>
      <p>${inv.invoice_number} · Status: ${statusLabel}</p>
    </div>
  </div>
  <div class="grid">
    <div class="box">
      <div class="label">Billed To</div>
      <div><strong>${inv.patient?.full_name ?? 'Patient'}</strong></div>
      <div class="sub">${inv.patient?.patient_number ?? ''} ${inv.patient?.phone ? `· ${inv.patient.phone}` : ''}</div>
    </div>
    <div class="box">
      <div class="label">Invoice Dates</div>
      <div>Issued: <strong>${formatDate(inv.issued_at)}</strong></div>
      <div class="sub">Due: ${formatDate(inv.due_at)}</div>
    </div>
  </div>
  <table>
    <thead>
      <tr>
        <th>Description</th>
        <th>Type</th>
        <th class="right">Qty</th>
        <th class="right">Unit Price</th>
        <th class="right">Amount</th>
      </tr>
    </thead>
    <tbody>${rows}</tbody>
  </table>
  <div class="summary">
    <div class="summary-row"><span>Subtotal</span><span>${formatCurrency(inv.subtotal)}</span></div>
    <div class="summary-row"><span>Discount</span><span>- ${formatCurrency(inv.discount_amount)}</span></div>
    <div class="summary-row"><span>Tax</span><span>+ ${formatCurrency(inv.tax_amount)}</span></div>
    <div class="summary-row summary-total"><span>Total Amount</span><span>${formatCurrency(inv.total_amount)}</span></div>
    <div class="summary-row"><span>Amount Paid</span><span>${formatCurrency(inv.paid_amount)}</span></div>
    <div class="summary-row"><strong>Remaining Balance</strong><strong>${formatCurrency(inv.remaining_balance)}</strong></div>
  </div>
  ${inv.notes ? `<p style="font-size:12px;color:#4b5563;margin-top:20px;"><strong>Notes:</strong> ${inv.notes}</p>` : ''}
  <div class="footer">Generated by Clinic Care Management System.</div>
</body>
</html>`)
  win.document.close()
  win.focus()
  win.print()
}
</script>

<template>
  <v-dialog :model-value="modelValue" max-width="760" @update:model-value="emit('update:modelValue', $event)">
    <v-card v-if="invoice" rounded="lg">
      <v-card-title class="d-flex align-center justify-space-between px-6 py-4 border-b">
        <div class="d-flex align-center ga-2">
          <v-icon icon="mdi-file-document-outline" color="primary" />
          <span class="text-h6 font-weight-bold">Printable Invoice — {{ invoice.invoice_number }}</span>
        </div>
        <v-btn icon="mdi-close" variant="text" @click="emit('update:modelValue', false)" />
      </v-card-title>

      <v-card-text class="pa-6">
        <div class="d-flex justify-space-between align-start mb-4">
          <div>
            <div class="text-h6 font-weight-bold text-primary">CLINIC CARE</div>
            <div class="text-caption text-medium-emphasis">Patient Billing Invoice</div>
          </div>
          <div class="text-right">
            <v-chip size="small" :color="INVOICE_STATUS_META[invoice.status]?.color" variant="tonal" class="mb-1">
              {{ INVOICE_STATUS_META[invoice.status]?.label ?? invoice.status }}
            </v-chip>
            <div class="text-caption text-medium-emphasis">Issued: {{ formatDate(invoice.issued_at) }}</div>
          </div>
        </div>

        <v-divider class="mb-4" />

        <div class="mb-4">
          <div class="text-caption text-medium-emphasis">BILLED TO</div>
          <div class="text-body-1 font-weight-bold">{{ invoice.patient?.full_name }}</div>
          <div class="text-caption text-medium-emphasis">{{ invoice.patient?.patient_number }}</div>
        </div>

        <v-table density="compact" class="border rounded-lg mb-4">
          <thead>
            <tr>
              <th>Description</th>
              <th>Type</th>
              <th class="text-right">Qty</th>
              <th class="text-right">Unit Price</th>
              <th class="text-right">Total</th>
            </tr>
          </thead>
          <tbody>
            <tr v-for="(item, idx) in invoice.items ?? []" :key="item.id ?? idx">
              <td>{{ item.description }}</td>
              <td class="text-capitalize">{{ item.item_type }}</td>
              <td class="text-right">{{ item.quantity }}</td>
              <td class="text-right">{{ formatCurrency(item.unit_price) }}</td>
              <td class="text-right font-weight-medium">{{ formatCurrency(item.line_total) }}</td>
            </tr>
          </tbody>
        </v-table>

        <div class="d-flex justify-end">
          <div style="width: 280px">
            <div class="d-flex justify-space-between text-body-2 mb-1">
              <span class="text-medium-emphasis">Subtotal</span>
              <span>{{ formatCurrency(invoice.subtotal) }}</span>
            </div>
            <div class="d-flex justify-space-between text-body-2 mb-1">
              <span class="text-medium-emphasis">Discount</span>
              <span>- {{ formatCurrency(invoice.discount_amount) }}</span>
            </div>
            <div class="d-flex justify-space-between text-body-2 mb-2">
              <span class="text-medium-emphasis">Tax</span>
              <span>+ {{ formatCurrency(invoice.tax_amount) }}</span>
            </div>
            <v-divider class="mb-2" />
            <div class="d-flex justify-space-between text-subtitle-1 font-weight-bold mb-1">
              <span>Total</span>
              <span>{{ formatCurrency(invoice.total_amount) }}</span>
            </div>
            <div class="d-flex justify-space-between text-body-2 text-success mb-1">
              <span>Paid</span>
              <span>{{ formatCurrency(invoice.paid_amount) }}</span>
            </div>
            <div class="d-flex justify-space-between text-body-2 font-weight-bold text-primary">
              <span>Remaining Balance</span>
              <span>{{ formatCurrency(invoice.remaining_balance) }}</span>
            </div>
          </div>
        </div>
      </v-card-text>

      <v-card-actions class="px-6 py-4 border-t">
        <v-spacer />
        <v-btn variant="text" @click="emit('update:modelValue', false)">Close</v-btn>
        <v-btn color="primary" variant="flat" prepend-icon="mdi-printer" @click="printInvoice">Print Invoice</v-btn>
      </v-card-actions>
    </v-card>
  </v-dialog>
</template>

